"""Generate vcdj_ctrlsw.c / vcdj_ctrlsw.h for SConscript VCDJ_CTRLSW = 'merged'.

    python vcdj_ctrlsw_gen.py              write both files next to this script
    python vcdj_ctrlsw_gen.py --check      exit 1 if the files on disk are stale
    python vcdj_ctrlsw_gen.py --map FILE   also write an output line -> vendor
                                           file:line map for offline checks

Mechanical transformation of the 'unity' build (vcdj_ctrlsw_unity.c):
  - vcdj_ctrlsw.h: dec_log.h, its overrides, and the closure of the vendor
    headers listed in src/common/rtl_vcdj_ctrlsw.h;
  - vcdj_ctrlsw.c: the 24 sources in the unity order, a header with an include
    guard expanded once, a header without one at every #include;
  - only conditionals on the fixed compile-contract macros and on include guards
    are resolved, every other conditional is kept as it is;
  - the PNG names the unity wrapper renames by macro are renamed in the text;
  - each source's own macros are #undef'd at the end of its segment, unless
    token-identical to a header definition.
Anything this cannot reproduce exactly stops the generator with an error.
"""
import argparse
import os
import re
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, 'software', 'source')
UNITY = os.path.join(HERE, 'vcdj_ctrlsw_unity.c')
VENDOR_H = os.path.normpath(os.path.join(HERE, '..', '..', 'inc', 'rtl_vcdj_vendor.h'))
ENTRY_H = os.path.normpath(os.path.join(HERE, '..', 'common', 'rtl_vcdj_ctrlsw.h'))
OUT_H = os.path.join(HERE, 'vcdj_ctrlsw.h')
OUT_C = os.path.join(HERE, 'vcdj_ctrlsw.c')
INCLUDE_DIRS = ['inc', 'config', 'common', 'jpeg', 'png']

# Defined unconditionally by rtl_vcdj_vendor.h (checked at run time). Macros it
# defines under #ifndef, such as VCDJ_ENABLE_ULTRA_SCALER, can be overridden on
# the command line and are left to the compiler.
FIXED_DEFINED = {
    'NON_PTHREAD_H': '', 'NDEBUG': '', 'FIFO_DATATYPE': 'void *', 'TILE_8x8': '',
    'USE_FAKE_RFC_TABLE': '', 'FAKE_RFC_TBL_LITTLE_ENDIAN': '',
    'SUPPORT_FLEXIBLE_FILTER': '', 'SUPPORT_TRNS': '',
}
# Deliberately undefined by the compile contract.
FIXED_UNDEFINED = {
    'VCD_LOGMSG', 'LIBVA_DEBUG', 'JPEGDEC_ASIC_TRACE', 'ASIC_TRACE_SUPPORT',
    'MODEL_SIMULATION', 'SUPPORT_VCMD', 'SUPPORT_MEM_SYNC', 'SUPPORT_DEC400',
    'ERROR_BUILD_SUPPORT', '_USE_VSI_STRING_', 'USE_64BIT_ENV',
    # Defined only by dwlthread.h under #ifndef NON_PTHREAD_H.
    '_HAVE_PTHREAD_H',
}
FIXED = set(FIXED_DEFINED) | FIXED_UNDEFINED

NOTE = ('/*\n'
        ' * GENERATED by src/ctrlsw/vcdj_ctrlsw_gen.py from the VeriSilicon sources in\n'
        ' * src/ctrlsw/software/source/; do not edit by hand. The merged copyright and\n'
        ' * license block at the top of this file stands for the per-file blocks of the\n'
        ' * vendor sources, which keep their own.\n'
        ' */')

IDENT = re.compile(r'[A-Za-z_]\w*')
DIRECTIVE = re.compile(r'\s*#\s*(\w+)\s*(.*)$', re.S)


class GenError(Exception):
    pass


def read(path):
    # latin-1 maps every byte to one character, so vendor text round-trips.
    with open(path, 'rb') as f:
        return f.read().decode('latin-1')


def rel(path):
    return os.path.relpath(path, SRC).replace('\\', '/')


# ---------------------------------------------------------------------------
# Lexing
# ---------------------------------------------------------------------------
def spans(text):
    """Yield (kind, start, end) with kind 'code', 'comment' or 'literal'."""
    i, n, start = 0, len(text), 0
    while i < n:
        c = text[i]
        if text.startswith('/*', i):
            j = text.find('*/', i + 2)
            j = n if j < 0 else j + 2
        elif text.startswith('//', i):
            j = i
            while True:
                k = text.find('\n', j)
                if k < 0:
                    j = n
                    break
                j = k
                if text[k - 1] != '\\':
                    break
                j = k + 1
        elif c in '"\'':
            j = i + 1
            while j < n and text[j] != c and text[j] != '\n':
                j += 2 if text[j] == '\\' else 1
            j = min(j + 1, n)
        else:
            i += 1
            continue
        if start < i:
            yield 'code', start, i
        yield ('literal' if c in '"\'' else 'comment'), i, j
        start = i = j
    if start < n:
        yield 'code', start, n


def code_idents(text):
    """Identifiers outside comments and literals."""
    for kind, a, b in spans(text):
        if kind == 'code':
            for m in IDENT.finditer(text, a, b):
                yield m.group(0)


def has_code(text):
    return any(kind != 'comment' and text[a:b].strip() for kind, a, b in spans(text))


def rename_code(text, names):
    pat = re.compile(r'\b(%s)\b' % '|'.join(sorted(names, key=len, reverse=True)))
    out = []
    for kind, a, b in spans(text):
        s = text[a:b]
        out.append(pat.sub(lambda m: names[m.group(1)], s) if kind == 'code' else s)
    return ''.join(out)


def logical_lines(text):
    """Yield (first line number, [physical lines], code) per logical line.

    `code` has comments blanked. A directive takes its backslash continuations
    and any block comment it opens, so dropping a directive drops those too.
    """
    blank, comments = [], []
    for kind, a, b in spans(text):
        s = text[a:b]
        blank.append(re.sub(r'[^\n]', ' ', s) if kind == 'comment' else s)
        if kind == 'comment':
            comments.append((a, b))
    code = ''.join(blank).split('\n')
    phys = text.split('\n')
    if phys[-1] == '':
        phys.pop()
        code.pop()
    open_at_eol, off, k = [], 0, 0
    for p in phys:
        off += len(p)
        while k < len(comments) and comments[k][1] <= off:
            k += 1
        open_at_eol.append(k < len(comments) and comments[k][0] < off)
        off += 1
    i = 0
    while i < len(phys):
        j = i
        if code[i].lstrip().startswith('#'):
            while j + 1 < len(phys) and (code[j].endswith('\\') or open_at_eol[j]):
                j += 1
        yield i + 1, phys[i:j + 1], ' '.join(c.rstrip('\\') for c in code[i:j + 1])
        i = j + 1


def tokens(s):
    return re.findall(r'[A-Za-z_]\w*|\d\w*|"(?:\\.|[^"])*"|\'(?:\\.|[^\'])*\'|##|#|\S', s)


# ---------------------------------------------------------------------------
# #if evaluation, three-valued: an int, or None when the value depends on a
# macro the generator does not resolve.
# ---------------------------------------------------------------------------
class Expr:
    LEVELS = [('==', '!='), ('<', '>', '<=', '>='), ('+', '-'), ('*', '/', '%')]

    def __init__(self, text, lookup):
        self.text = text
        self.t = re.findall(r'\d\w*|[A-Za-z_]\w*|&&|\|\||==|!=|<=|>=|<<|>>|\S', text)
        self.i = 0
        self.lookup = lookup

    def fail(self):
        raise GenError('cannot evaluate #if %s' % ' '.join(self.text.split()))

    def peek(self):
        return self.t[self.i] if self.i < len(self.t) else None

    def take(self, want=None):
        tok = self.peek()
        if tok is None or (want is not None and tok != want):
            self.fail()
        self.i += 1
        return tok

    def run(self):
        v = self.lor()
        if self.peek() is not None:
            self.fail()
        return v

    def lor(self):
        v = self.land()
        while self.peek() == '||':
            self.take()
            w = self.land()
            v = 1 if (v or w) else (None if v is None or w is None else 0)
        return v

    def land(self):
        v = self.binary(0)
        while self.peek() == '&&':
            self.take()
            w = self.binary(0)
            v = 0 if (v == 0 or w == 0) else (None if v is None or w is None else 1)
        return v

    def binary(self, level):
        if level == len(self.LEVELS):
            return self.unary()
        v = self.binary(level + 1)
        while self.peek() in self.LEVELS[level]:
            op = self.take()
            w = self.binary(level + 1)
            if v is None or w is None:
                v = None
            elif op in ('/', '%') and w == 0:
                self.fail()
            else:
                v = int({'==': v == w, '!=': v != w, '<': v < w, '>': v > w,
                         '<=': v <= w, '>=': v >= w, '+': v + w, '-': v - w,
                         '*': v * w, '/': int(v / w), '%': v % w}[op])
        return v

    def unary(self):
        tok = self.take()
        if tok in ('!', '-', '+', '~'):
            v = self.unary()
            return None if v is None else {'!': int(not v), '-': -v, '+': v, '~': ~v}[tok]
        if tok == '(':
            v = self.lor()
            self.take(')')
            return v
        if tok == 'defined':
            paren = self.peek() == '('
            if paren:
                self.take()
            name = self.take()
            if paren:
                self.take(')')
            return self.lookup(name, True)
        m = re.match(r'(0[xX][0-9a-fA-F]+|\d+)[uUlL]*$', tok)
        if m:
            return int(m.group(1), 0)
        if IDENT.fullmatch(tok):
            return self.lookup(tok, False)
        self.fail()


# ---------------------------------------------------------------------------
# Expansion
# ---------------------------------------------------------------------------
class Generator:
    def __init__(self):
        self.guard_of = {}           # header path -> guard macro or None
        self.guard_names = set()
        self.guards_defined = set()
        self.expanded = set()
        self.macros = {}             # name -> (origin path, body tokens), as in scope now
        self.own = {}                # name -> body: macros the current .c defined itself
        self.kept_depth = 0          # nesting depth of kept (unresolved) conditionals
        self.unresolved_includes = []

    def guard(self, path):
        """Guard macro if everything but leading #includes sits in one
        #ifndef X / #define X ... #endif group, else None."""
        if path in self.guard_of:
            return self.guard_of[path]
        dirs = [c for _, _, c in logical_lines(read(path)) if c.lstrip().startswith('#')]
        kws = [DIRECTIVE.match(d).group(1) for d in dirs]
        g = None
        k = next((i for i, kw in enumerate(kws) if kw != 'include'), None)
        if k is not None and k + 1 < len(dirs):
            m = re.match(r'\s*#\s*(?:ifndef\s+(\w+)|if\s+!\s*defined\s*\(\s*(\w+)\s*\))\s*$',
                         dirs[k])
            name = m and (m.group(1) or m.group(2))
            if name and re.match(r'\s*#\s*define\s+%s\s*$' % name, dirs[k + 1]):
                depth = 0
                for i in range(k, len(dirs)):
                    depth += kws[i] in ('if', 'ifdef', 'ifndef')
                    depth -= kws[i] == 'endif'
                    if depth == 0:
                        break
                if depth == 0 and i == len(dirs) - 1:
                    g = name
        self.guard_of[path] = g
        if g:
            self.guard_names.add(g)
        return g

    def lookup(self, name, as_defined):
        if name in FIXED_DEFINED:
            body = FIXED_DEFINED[name]
            if as_defined:
                return 1
            return int(body, 0) if re.fullmatch(r'0[xX][0-9a-fA-F]+|\d+', body) else None
        if name in FIXED_UNDEFINED:
            return 0
        if name in self.guard_names and as_defined:
            return int(name in self.guards_defined)
        return None

    def evaluate(self, kw, arg):
        if kw == 'ifdef':
            arg = 'defined(%s)' % arg.strip()
        elif kw == 'ifndef':
            arg = '!defined(%s)' % arg.strip()
        if not set(IDENT.findall(arg)) & (FIXED | self.guard_names):
            return None
        return Expr(arg, self.lookup).run()

    def resolve(self, name, including):
        for d in [os.path.dirname(including)] + [os.path.join(SRC, x) for x in INCLUDE_DIRS]:
            p = os.path.normpath(os.path.join(d, name))
            if os.path.isfile(p):
                return p
        return None

    def on_define(self, path, no, arg):
        m = re.match(r'(\w+)(\([^)]*\))?(.*)$', arg, re.S)
        name, body = m.group(1), tokens((m.group(2) or '') + ' ' + m.group(3))
        where = '%s:%d' % (rel(path), no)
        if name in FIXED:
            raise GenError('%s: #define of contract macro %s' % (where, name))
        prev = self.macros.get(name)
        if path.endswith('.c'):
            if prev and prev[0].endswith('.h'):
                if prev[1] != body:
                    raise GenError('%s: redefines %s from %s differently'
                                   % (where, name, rel(prev[0])))
                return              # same as the header's: stays defined
            self.own[name] = body
        elif name in self.own:
            if self.own[name] != body:
                raise GenError('%s: redefines %s, defined earlier by the source, differently'
                               % (where, name))
            del self.own[name]      # the header owns it now: not #undef'd later
        self.macros[name] = (path, body)
        if name in self.guard_names and not self.kept_depth:
            self.guards_defined.add(name)

    def on_undef(self, path, no, name):
        where = '%s:%d' % (rel(path), no)
        if name in FIXED:
            raise GenError('%s: #undef of contract macro %s' % (where, name))
        prev = self.macros.get(name)
        if path.endswith('.c') and prev and prev[0].endswith('.h'):
            raise GenError('%s: #undef of %s from %s; later segments would lose it'
                           % (where, name, rel(prev[0])))
        self.macros.pop(name, None)
        self.own.pop(name, None)
        self.guards_defined.discard(name)

    def expand(self, path):
        """Return [(line, (path, line number))] for `path`, includes expanded."""
        again = path in self.expanded
        self.expanded.add(path)
        out = []
        # Group states: 'pending' no branch chosen yet, nothing emitted;
        # 'taken' a known-true branch, emitted without directives; 'kept' an
        # #if line was emitted; 'done' no further branch can be active;
        # 'dead' the enclosing group is inactive.
        stack = []
        active = True
        for no, lines, code in logical_lines(read(path)):
            here = [(l, (path, no + i)) for i, l in enumerate(lines)]
            m = DIRECTIVE.match(code) if code.lstrip().startswith('#') else None
            kw, arg = (m.group(1), m.group(2)) if m else (None, '')
            if kw in ('if', 'ifdef', 'ifndef'):
                g = {'parent': active, 'state': 'dead', 'kept': False}
                stack.append(g)
                if active:
                    v = self.evaluate(kw, arg)
                    if v is None:
                        g.update(state='kept', kept=True)
                        self.kept_depth += 1
                        out += here
                    elif v:
                        g['state'] = 'taken'
                    else:
                        g['state'] = 'pending'
                        active = False
                continue
            if kw in ('elif', 'else'):
                if not stack:
                    raise GenError('%s:%d: #%s without #if' % (rel(path), no, kw))
                g = stack[-1]
                state = g['state']
                if state in ('dead', 'done', 'taken'):
                    if state == 'taken':
                        g['state'] = 'done'
                    active = False
                    continue
                v = 1 if kw == 'else' else self.evaluate('if', arg)
                if state == 'pending':
                    if v is None:
                        g.update(state='kept', kept=True)
                        self.kept_depth += 1
                        out += [(re.sub(r'#(\s*)elif', r'#\1if', here[0][0], count=1),
                                 here[0][1])] + here[1:]
                    elif v:
                        g['state'] = 'taken'
                    active = v != 0
                else:   # kept
                    if v is None:
                        out += here
                    elif v:
                        out += here if kw == 'else' else [('#else', here[0][1])]
                        g['state'] = 'done'
                    active = v != 0
                continue
            if kw == 'endif':
                if not stack:
                    raise GenError('%s:%d: #endif without #if' % (rel(path), no))
                g = stack.pop()
                if g['kept']:
                    self.kept_depth -= 1
                    out += here
                active = g['parent']
                continue
            if not active:
                continue
            if kw == 'include':
                im = re.match(r'"([^"]+)"', arg.strip())
                inc = im and self.resolve(im.group(1), path)
                if not im:
                    out += here
                elif inc is None:
                    # Not a vendor file: a system header, or (under a kept
                    # conditional) one the selective import left out.
                    self.unresolved_includes.append('%s:%d %s' % (rel(path), no, im.group(1)))
                    out += here
                else:
                    if self.kept_depth and self.guard(inc) and inc not in self.expanded:
                        raise GenError('%s:%d: guarded %s is first included under an '
                                       'unresolved conditional' % (rel(path), no, rel(inc)))
                    self.guard(inc)
                    out += self.expand(inc)
                continue
            if kw == 'define':
                self.on_define(path, no, arg)
            elif kw == 'undef':
                self.on_undef(path, no, arg.split()[0])
            out += here
        if stack:
            raise GenError('%s: unterminated #if' % rel(path))
        if again:
            body = '\n'.join(l for l, _ in out)
            if not has_code(body):
                return []
            # A header without an include guard, expanded again: drop the whole
            # lines of leading comments (its license block), keep the rest.
            first = next(a for kind, a, b in spans(body) if kind != 'comment' and body[a:b].strip())
            first += len(body[first:]) - len(body[first:].lstrip())
            lead = body.count('\n', 0, first)
            if body[body.rfind('\n', 0, first) + 1:first].strip():
                lead = 0        # a comment shares the first code line; keep all
            out = [('/* %s again: it has no include guard */' % rel(path), None)] + out[lead:]
        return out


# ---------------------------------------------------------------------------
def parse_inputs():
    unity = read(UNITY)
    srcs = re.findall(r'^#include "software/source/([^"]+\.c)"', unity, re.M)
    if len(srcs) != 24:
        raise GenError('expected 24 sources in vcdj_ctrlsw_unity.c, found %d' % len(srcs))
    renames = dict(re.findall(r'^#define\s+(\w+)\s+(Png_\w+)\s*$', unity, re.M))
    first_png = next(i for i, s in enumerate(srcs) if s.startswith('png/'))
    m = re.search(r'^#else[^\n]*\n(.*?)^#endif', read(ENTRY_H), re.S | re.M)
    headers = re.findall(r'^\s*#\s*include\s+"([^"]+\.h)"', m.group(1), re.M) if m else []
    if not headers:
        raise GenError('no vendor header list in the #else branch of rtl_vcdj_ctrlsw.h')
    vendor_h = read(VENDOR_H)
    for name, body in FIXED_DEFINED.items():
        if not re.search(r'^#define %s[ \t]*%s[ \t]*$' % (name, re.escape(body)), vendor_h, re.M):
            raise GenError('rtl_vcdj_vendor.h no longer defines %s as "%s"' % (name, body))
    for name in FIXED_UNDEFINED:
        if re.search(r'#\s*define\s+%s\b' % name, vendor_h):
            raise GenError('rtl_vcdj_vendor.h defines %s, which the contract leaves '
                           'undefined' % name)
    return srcs, renames, first_png, headers


def generate():
    srcs, renames, first_png, headers = parse_inputs()
    gen = Generator()

    # dec_log.h comes first, as rtl_vcdj_vendor.h includes it ahead of everything
    # in the other two modes, and its overrides must follow it directly.
    h = [(NOTE, None), ('', None), ('#ifndef VCDJ_CTRLSW_H', None),
         ('#define VCDJ_CTRLSW_H', None), ('', None)]
    dec_log = os.path.join(SRC, 'inc', 'dec_log.h')
    gen.guard(dec_log)
    h += gen.expand(dec_log)
    h += [('', None), ('#include "rtl_vcdj_vendor_log.h"', None)]
    for name in headers:
        p = gen.resolve(name, os.path.join(SRC, 'inc', '_'))
        if p is None:
            raise GenError('rtl_vcdj_ctrlsw.h names unknown vendor header %s' % name)
        gen.guard(p)
        h += gen.expand(p)
    h += [('', None), ('#endif /* VCDJ_CTRLSW_H */', None)]
    shared = set(code_idents('\n'.join(l for l, _ in h))) & set(renames)
    if shared:
        raise GenError('renamed names %s appear in vcdj_ctrlsw.h' % sorted(shared))

    c = [(NOTE, None), ('', None), ('#include "vcdj_ctrlsw.h"', None)]
    early = {}
    for k, s in enumerate(srcs):
        if k == first_png:
            # The unity wrapper's rename macros also reach macro bodies defined
            # before the PNG part; the text rename does not.
            early = {n for n, (_, b) in gen.macros.items() if set(b) & set(renames)}
        gen.own = {}
        seg = gen.expand(os.path.join(SRC, s))
        undefs = list(gen.own)
        for n in undefs:
            gen.macros.pop(n, None)
        if k >= first_png:
            seg = [(rename_code(l, renames), o) for l, o in seg]
            used = set(code_idents('\n'.join(l for l, _ in seg))) & early
            if used:
                raise GenError('%s uses %s, whose body names a renamed identifier'
                               % (s, sorted(used)))
            undefs = [renames.get(n, n) for n in undefs]
        bar = '=' * 76
        c += [('', None), ('/*%s*' % bar, None), (' * software/source/%s' % s, None),
              (' *%s*/' % bar, None)]
        c += seg
        if undefs:
            c += [('', None)] + [('#undef %s' % n, None) for n in undefs]
    return squeeze(h), squeeze(c), gen


def squeeze(lines):
    """One line per entry; runs of blank lines collapsed to one."""
    out = []
    for l, o in lines:
        for part in (l.split('\n') if o is None else [l]):
            if not part.strip() and out and not out[-1][0].strip():
                continue
            out.append((part.rstrip() if o is None else part, o))
    return out


def render(lines):
    return ''.join(l + '\n' for l, _ in lines)


def main():
    ap = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    ap.add_argument('--check', action='store_true', help='fail if the files on disk are stale')
    ap.add_argument('--map', metavar='FILE', help='write the output line -> vendor line map')
    a = ap.parse_args()
    try:
        h, c, gen = generate()
    except GenError as e:
        sys.exit('vcdj_ctrlsw_gen: error: %s' % e)
    files = ((OUT_H, h), (OUT_C, c))
    if a.map:
        with open(a.map, 'w') as f:
            for p, lines in files:
                for n, (_, o) in enumerate(lines, 1):
                    if o:
                        f.write('%s\t%d\t%s\t%d\n' % (os.path.basename(p), n, rel(o[0]), o[1]))
    if a.check:
        # The files on disk also carry the prune list, so compare against the
        # pruned output; vcdj_ctrlsw_prune.py owns that and reports precisely.
        prune = os.path.join(HERE, 'vcdj_ctrlsw_prune.py')
        if os.path.isfile(prune):
            sys.exit(subprocess.call([sys.executable, prune, '--check']))
        stale = [p for p, t in files if not os.path.isfile(p) or read(p) != render(t)]
        for p in stale:
            print('vcdj_ctrlsw_gen: %s is stale; rerun the generator' % os.path.basename(p))
        sys.exit(1 if stale else 0)
    for p, t in files:
        with open(p, 'wb') as f:
            f.write(render(t).encode('latin-1'))
        print('wrote %s (%d lines)' % (os.path.basename(p), len(t)))
    for u in gen.unresolved_includes:
        print('note: kept #include under an unresolved conditional: %s' % u)


