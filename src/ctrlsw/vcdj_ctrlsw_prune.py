"""Apply the prune list to the generated vcdj_ctrlsw.c / vcdj_ctrlsw.h.

    python vcdj_ctrlsw_prune.py              generate, prune, write both files
    python vcdj_ctrlsw_prune.py --check      exit 1 if the files on disk differ
    python vcdj_ctrlsw_prune.py --map FILE   also write an output line -> vendor
                                             file:line map of the pruned files

This runs after vcdj_ctrlsw_gen.py: the generator reproduces the vendor build
and stays checkable, and everything deleted from it lives in
vcdj_ctrlsw_prune.json as data. Rules locate code by name and by brace
structure, never by line number, so adding a source to a segment or regrouping
the output does not invalidate them.

One action works on text instead: merge_license collapses the per-file vendor
license blocks into one at the top of each output file. It keeps every clause
verbatim and merges only the copyright lines, so the notice a file has to
carry stays complete, and it stops with an error on a clause it has not seen.
"""
import argparse
import json
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
OUT_H = os.path.join(HERE, 'vcdj_ctrlsw.h')
OUT_C = os.path.join(HERE, 'vcdj_ctrlsw.c')
RULES = os.path.join(HERE, 'vcdj_ctrlsw_prune.json')

sys.path.insert(0, HERE)
import vcdj_ctrlsw_gen as gen  # noqa: E402

GUARD_OPEN = re.compile(r'\s*#\s*(?:if|ifdef|ifndef)\b')
GUARD_ANY = re.compile(r'\s*#\s*(if|ifdef|ifndef|endif)\b')

# A license block is a comment of its own (nothing else on its first or last
# line) that carries a copyright line. After the box drawing is stripped, the
# copyright lines are merged across blocks and each distinct clause text is
# identified by its line count and kept once.
COPYRIGHT = re.compile(r'^copyright\b', re.I)
METADATA = re.compile(r'^(?:description|filename|file name|purpose|module|author|'
                      r'function)\s*:', re.I)
GENERATED_NOTE = re.compile(r'GENERATED by src/ctrlsw/vcdj_ctrlsw_gen\.py')
# Two box styles carry these blocks. The `--` style draws its box with dashes
# and leaves `* ` as a list bullet, so only the dashes go; the `*` style uses
# one leading `*` per line as the comment marker.
DASH_BOX = re.compile(r'^\s*--\s?|(?:\s*--\s*)+$')
STAR_BOX = re.compile(r'^\s*(?:/\*+|\*+|//+)\s?|(?:\*+/|//+)\s*$')
# Clause texts differ only by line count after the box is stripped, and each
# count is one text, so a count the rule does not list is an unknown clause.
CLAUSE = {'bsd3': 22, 'bsd3-proprietary': 28, 'verisilicon-restricted': 17}


class PruneError(Exception):
    pass


def read(path):
    with open(path, 'rb') as f:
        return f.read().decode('latin-1')


def code_lines(lines):
    """The lines with comments and literals blanked, so brace counting is safe."""
    text = '\n'.join(lines)
    blank = [(kind, a, b) for kind, a, b in gen.spans(text) if kind != 'code']
    out, pos = [], 0
    for kind, a, b in blank:
        out.append(text[pos:a])
        out.append(re.sub(r'[^\n]', ' ', text[a:b]))
        pos = b
    out.append(text[pos:])
    return ''.join(out).split('\n')


def file_scope_hits(code, name):
    """[(first line, terminator line, is_definition)] for `name` at column 0.

    A file-scope line naming the function is a definition if `{` comes before
    `;` and a prototype otherwise. Some vendor files declare their own
    functions before defining them, so both forms occur.
    """
    pat = re.compile(r'^[A-Za-z_][\w \t\*]*\b%s\s*\(' % re.escape(name))
    hits = []
    for i, l in enumerate(code):
        if not pat.match(l):
            continue
        for j in range(i, len(code)):
            if '{' in code[j]:
                hits.append((i, j, True))
                break
            if ';' in code[j]:
                hits.append((i, j, False))
                break
    return hits


def find_definition(code, name, where):
    """(first line, opening brace line) of the definition of `name`."""
    defs = [h for h in file_scope_hits(code, name) if h[2]]
    if len(defs) != 1:
        raise PruneError('%s: %s: expected 1 definition, found %d at lines %s'
                         % (where, name, len(defs), [h[0] + 1 for h in defs]))
    return defs[0][0], defs[0][1]


def match_brace(code, open_line):
    """Line of the brace that closes the one on `open_line`."""
    depth = 0
    for i in range(open_line, len(code)):
        depth += code[i].count('{') - code[i].count('}')
        if depth < 0:
            raise PruneError('unbalanced } at line %d' % (i + 1))
        if depth == 0:
            return i
    raise PruneError('unterminated body from line %d' % (open_line + 1))


def guard_span(lines, lo, hi):
    """Extend [lo, hi] over a #if / #ifdef / #ifndef that wraps it exactly."""
    if lo == 0 or not GUARD_OPEN.match(lines[lo - 1]):
        return lo, hi
    start = lo - 1
    depth = 0
    for i in range(start, len(lines)):
        m = GUARD_ANY.match(lines[i])
        if not m:
            continue
        if m.group(1) == 'endif':
            depth -= 1
            if depth == 0:
                if i < hi:
                    raise PruneError('guard starting at line %d closes before the '
                                     'function body ends' % (start + 1))
                return start, max(hi, i)
        else:
            depth += 1
    raise PruneError('guard starting at line %d has no #endif' % (start + 1))


def delete_function(rule, doc, which):
    name = rule['name']
    lines = doc['lines']
    code = code_lines(lines)
    start, open_line = find_definition(code, name, which)
    hi = match_brace(code, open_line)
    # A comment block directly abutting the definition documents it, so it
    # goes too; left behind it would appear to document its successor.
    j = start - 1
    while j >= 0 and lines[j].strip() and not code[j].strip():
        j -= 1
    lo, hi = guard_span(lines, j + 1, hi)
    if hi + 1 < len(lines) and not lines[hi + 1].strip():
        hi += 1          # the blank line after the body goes too
    del doc['lines'][lo:hi + 1]
    del doc['origin'][lo:hi + 1]
    # A prototype the same file carries for the function it just lost would
    # count as a dangling reference in the check below, so drop it here.
    code = code_lines(doc['lines'])
    for first, last, is_definition in reversed(file_scope_hits(code, name)):
        if not is_definition:
            del doc['lines'][first:last + 1]
            del doc['origin'][first:last + 1]


def delete_declaration(rule, doc):
    name = rule['name']
    lines = doc['lines']
    hits = file_scope_hits(code_lines(lines), name)
    if not hits:
        if rule.get('header', True):
            raise PruneError('vcdj_ctrlsw.h: %s: declaration not found' % name)
        return
    if len(hits) != 1 or hits[0][2]:
        raise PruneError('vcdj_ctrlsw.h: %s: expected 1 declaration, found %d at '
                         'lines %s' % (name, len(hits), [h[0] + 1 for h in hits]))
    lo, hi, _ = hits[0]
    # A #ifdef / #endif pair that wraps only this declaration goes with it.
    if (lo > 0 and GUARD_OPEN.match(lines[lo - 1]) and hi + 1 < len(lines)
            and re.match(r'\s*#\s*endif\b', lines[hi + 1])):
        lo, hi = lo - 1, hi + 1
    del lines[lo:hi + 1]
    del doc['origin'][lo:hi + 1]


def delete_region(rule, doc, which):
    """Delete a run of lines located by two anchors.

    Used for data that only the deleted functions used and that carries no
    declaration in the header, so a name rule cannot reach it. Each anchor is
    one regex matched against a single line and must hit exactly once.

    `after` / `until` keep their own lines and delete what lies between them;
    `first` / `last` delete their own lines too, plus the one blank line above
    `first` that separated the run from what preceded it.
    """
    lines = doc['lines']
    code = code_lines(lines)

    def only(anchor):
        pat = re.compile(anchor)
        hits = [i for i, l in enumerate(code) if pat.search(l)]
        if len(hits) != 1:
            raise PruneError('%s: %r matches %d lines, the rule needs exactly one'
                             % (which, anchor, len(hits)))
        return hits[0]

    if 'first' in rule:
        lo, hi = only(rule['first']), only(rule['last'])
        if lo > 0 and not lines[lo - 1].strip():
            lo -= 1
        hi += 1          # exclusive end, the last line goes too
    else:
        lo, hi = only(rule['after']) + 1, only(rule['until'])
    if hi <= lo:
        raise PruneError('%s: region %s is empty or reversed' % (which, rule))
    del lines[lo:hi]
    del doc['origin'][lo:hi]


def dead_regions(code):
    """Line indices inside an `#if 0` block that has no #else / #elif.

    A call there is not compiled, so deleting its target leaves nothing
    dangling. Any #else or #elif makes the block live again and it is not
    marked, which keeps this check conservative.
    """
    dead, stack = set(), []
    for i, l in enumerate(code):
        m = GUARD_ANY.match(l)
        if not m:
            continue
        kw = m.group(1)
        if kw in ('if', 'ifdef', 'ifndef'):
            stack.append([i, False, kw == 'if' and l.split(None, 1)[1].strip() == '0'])
        elif kw == 'endif' and stack:
            start, live, was_zero = stack.pop()
            if was_zero and not live:
                dead.update(range(start, i + 1))
        elif stack:
            stack[-1][1] = True
    return dead


def check_no_code_references(rule, doc, which):
    """The deleted name must not survive in live code; comments may mention it."""
    name = rule['name']
    pat = re.compile(r'\b%s\b' % re.escape(name))
    code = code_lines(doc['lines'])
    dead = dead_regions(code)
    left = [i + 1 for i, l in enumerate(code) if i not in dead and pat.search(l)]
    if left:
        raise PruneError('%s: %s still referenced in live code at lines %s; the rule '
                         'would leave a dangling use' % (which, name, left[:5]))


def strip_decor(line):
    """The line without its box drawing, inner spacing kept."""
    t = line.strip()
    if set(t) <= set('-/*'):
        return ''           # a pure box border, whatever its style
    if t.startswith('/*') or t.startswith('*') or t.startswith('//'):
        return STAR_BOX.sub('', t).strip()
    u = DASH_BOX.sub('', t).strip()
    return re.sub(r'\s{2,}', ' ', u)    # the dash box pads to a fixed width


def split_block(lines, lo, hi):
    """(copyright lines, clause lines) of the license block on lines lo..hi.

    Empty strings in the clause mark the blank separator lines of the box, so
    the merged block keeps the vendor's own paragraph breaks.
    """
    inner = [strip_decor(x) for x in lines[lo:hi + 1]]
    if not inner[0]:
        inner = inner[1:]   # the opening `/*` line
    if inner and not inner[-1]:
        inner = inner[:-1]  # the closing `*/` line
    body, blank = [], False
    for l in inner:
        if l:
            body.append(l)
            blank = False
        elif body and not blank:
            body.append('')
            blank = True
    while body and not body[-1]:
        body.pop()
    while body and METADATA.match(body[-1]):
        body.pop()          # file metadata that the vendor put inside the box
    while body and not body[-1]:
        body.pop()
    while body and not body[0]:
        body.pop(0)
    cr = [l for l in body if l and COPYRIGHT.match(l)]
    cl = [l for l in body if not l or not COPYRIGHT.match(l)]
    while cl and not cl[0]:
        cl.pop(0)
    while cl and not cl[-1]:
        cl.pop()
    if not cr:
        raise PruneError('license block at line %d has no copyright line' % (lo + 1))
    return cr, cl


def find_license_blocks(lines):
    """[(lo, hi, copyright lines, clause lines)] for every license block."""
    text = '\n'.join(lines)
    out = []
    for kind, a, b in gen.spans(text):
        if kind != 'comment':
            continue
        seg = text[a:b]
        if not re.search(r'copyright', seg, re.I):
            continue
        lo, hi = text.count('\n', 0, a), text.count('\n', 0, b - 1)
        bol, eol = text.rfind('\n', 0, a) + 1, text.find('\n', b)
        eol = len(text) if eol < 0 else eol
        if text[bol:a].strip() or text[b:eol].strip():
            raise PruneError('line %d: code shares a line with a license block'
                             % (lo + 1))
        if GENERATED_NOTE.search(seg):
            continue        # the generator's own header, not a vendor block
        cr, cl = split_block(lines, lo, hi)
        out.append((lo, hi, cr, cl))
    return out


def merge_license(rule, doc, which):
    """Replace every per-file license block with one merged block at the top.

    Each clause is kept verbatim once, so nothing a per-file notice said is
    lost; only the copyright lines, which differ per file, are merged. The
    merged block goes in front of the whole document, above the generated
    header and the include guard.
    """
    lines = doc['lines']
    blocks = find_license_blocks(lines)
    n = rule['blocks'][which]
    if len(blocks) != n:
        raise PruneError('%s: found %d license blocks, the rule expects %d; a new '
                         'vendor drop may have changed the text, recheck it'
                         % (which, len(blocks), n))
    holders, clauses = [], {}
    for lo, _, cr, cl in blocks:
        for h in cr:
            if h not in holders:
                holders.append(h)
        key = tuple(cl)
        if key in clauses:
            continue
        name = next((k for k, v in CLAUSE.items() if v == len(cl)), None)
        if name is None:
            raise PruneError('%s: %d-line clause at line %d matches no known '
                             'license text; check it before merging'
                             % (which, len(cl), lo + 1))
        clauses[key] = name
    if sorted(clauses.values()) != sorted(rule['clauses'][which]):
        raise PruneError('%s: clause set is %s, the rule expects %s'
                         % (which, sorted(clauses.values()),
                            sorted(rule['clauses'][which])))
    if holders != rule['holders'][which]:
        raise PruneError('%s: copyright holders are %s, the rule expects %s'
                         % (which, holders, rule['holders'][which]))
    for lo, hi, _, _ in reversed(blocks):
        if hi + 1 < len(lines) and not lines[hi + 1].strip():
            hi += 1          # the blank line after the block goes too
        del lines[lo:hi + 1]
        del doc['origin'][lo:hi + 1]

    def emit(x):
        if not x:
            return ' *'
        if x.startswith('*'):
            return (' * ' + x).rstrip()      # a list bullet line reads " * * ..."
        return (' * ' + x).rstrip()

    head = ['/*'] + [emit(x) for x in rule['header']] + [' *']
    head += [emit(h) for h in holders] + [' *']
    for i, key in enumerate(clauses):
        if i:
            head.append(' *')
        head += [emit(x) for x in key]
    head += [' */', '']
    doc['lines'][0:0] = head
    doc['origin'][0:0] = [None] * len(head)


ACTIONS = {
    'delete_function': (delete_function, check_no_code_references),
    'delete_region': (delete_region, None),
    'merge_license': (merge_license, None),
}
# Actions that touch no header declaration; the rest name a function.
NO_HEADER = {'merge_license', 'delete_region'}


def apply_rules(h, c, rules):
    docs = {'vcdj_ctrlsw.h': {'lines': [l for l, _ in h], 'origin': [o for _, o in h]},
            'vcdj_ctrlsw.c': {'lines': [l for l, _ in c], 'origin': [o for _, o in c]}}
    for n, rule in enumerate(rules, 1):
        action = rule.get('action')
        if action not in ACTIONS:
            raise PruneError('rule %d: unknown action %r' % (n, action))
        fn, verify = ACTIONS[action]
        for which in rule.get('files') or ['vcdj_ctrlsw.c']:
            fn(rule, docs[which], which)
            if verify:
                verify(rule, docs[which], which)
        if action not in NO_HEADER:
            delete_declaration(rule, docs['vcdj_ctrlsw.h'])
            verify(rule, docs['vcdj_ctrlsw.h'], 'vcdj_ctrlsw.h')
    return (list(zip(docs['vcdj_ctrlsw.h']['lines'], docs['vcdj_ctrlsw.h']['origin'])),
            list(zip(docs['vcdj_ctrlsw.c']['lines'], docs['vcdj_ctrlsw.c']['origin'])))


def main():
    ap = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    ap.add_argument('--check', action='store_true', help='fail if the files on disk differ')
    ap.add_argument('--map', metavar='FILE', help='write the pruned output line -> vendor line map')
    a = ap.parse_args()
    try:
        h, c, _ = gen.generate()
        rules = json.loads(read(RULES))['rules']
        h, c = apply_rules(h, c, rules)
    except gen.GenError as e:
        sys.exit('vcdj_ctrlsw_prune: generator error: %s' % e)
    except (PruneError, ValueError, KeyError) as e:
        sys.exit('vcdj_ctrlsw_prune: error: %s' % e)

    files = ((OUT_H, h), (OUT_C, c))
    if a.map:
        with open(a.map, 'w') as f:
            for p, lines in files:
                for n, (_, o) in enumerate(lines, 1):
                    if o:
                        f.write('%s\t%d\t%s\t%d\n' % (os.path.basename(p), n,
                                                      gen.rel(o[0]), o[1]))
    if a.check:
        stale = [p for p, t in files
                 if not os.path.isfile(p) or read(p) != ''.join(l + '\n' for l, _ in t)]
        for p in stale:
            print('vcdj_ctrlsw_prune: %s is stale; rerun the generator and this script'
                  % os.path.basename(p))
        sys.exit(1 if stale else 0)
    for p, t in files:
        with open(p, 'wb') as f:
            f.write(''.join(l + '\n' for l, _ in t).encode('latin-1'))
        print('wrote %s (%d lines)' % (os.path.basename(p), len(t)))


if __name__ == '__main__':
    main()
